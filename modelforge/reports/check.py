"""核对报告正文里的数字 —— 找出那些在过程记录里**没有出处**的。

════════════════════════════════════════════════════════════════════════
这个检查想解决什么
════════════════════════════════════════════════════════════════════════

报告的正文由模型写，而系统提示词里有一条硬规矩：「绝不编造数据」。
问题是**这条规矩没有执行者** —— 模型说它没编，没人能验证。

这里能验证。报告里的每一段正文都配着一段材料（`SectionPlan.brief`），
那是模型写这段文字时**唯一能看到的东西**。所以：

    正文里出现了一个像数据的数字，而材料里没有 → 它从哪来的？

════════════════════════════════════════════════════════════════════════
⚠️ 判据必须**弱**，措辞必须**弱**
════════════════════════════════════════════════════════════════════════

它一定会误报。三种最常见的合法情况：

    · **派生值** —— 材料给的是 0.1267，正文写「12.67%」
    · **差值** —— 材料给的是 120 和 135，正文写「相差 15」
    · **四舍五入** —— 材料给的是 0.42317，正文写「约 0.423」

这三种都是**好的写作**，不是作弊。所以：

  判据弱   —— 只挑「带小数点」或「三位及以上整数」的数字。
             「第 3 步」「共 5 个指标」这种不会进来。
  措辞弱   —— 界面上说的是「**找不到出处，请你自己扫一眼**」，
             不是「模型编造了数字」。

一个动不动喊狼来了的检查比没有检查更糟：用户会学会无视它，
于是它连真话也传不到了。这跟 M5b 那个「文件可能已经不在了」的假报错
是同一个教训的正面用法 —— **报错文案的分寸，决定了它是被相信还是被忽略。**
"""

from __future__ import annotations

import re

__all__ = ["find_unverified_numbers"]

_NUMBER = re.compile(r"\d+(?:\.\d+)?")


def _looks_like_data(token: str) -> bool:
    """这个数字像不像「从数据里来的」。

    两条判据，都刻意保守：

        带小数点      0.4231 / 12.7 —— 几乎一定是算出来的
        三位及以上    100 / 2024     —— 序数不会这么长

    一位数和两位数的整数一律放过（「第 3 步」「5 个指标」「4 个评价对象」），
    那些占误报的绝大多数，而它们恰恰是最不可能被编造的。
    """
    return "." in token or len(token) >= 3


def _values(text: str) -> set[float]:
    """把一段文本里所有数字解析成 float 集合。

    用 float 而不是字符串比对，是为了让 `0.42` 和 `0.4200` 算作同一个数 ——
    模型把材料里的 `0.4200` 写成 `0.42` 是**正常的**，不该报警。

    不需要容差：一个十进制字面量转成 double 的结果是确定的，
    所以「同一个数」必然转成同一个 float。反过来 `0.1 + 0.2` 写成 `0.3`
    确实会被标出来 —— 那是**该**标的（模型在替材料做四舍五入）。
    """
    values: set[float] = set()
    for token in _NUMBER.findall(text):
        try:
            values.add(float(token))
        except ValueError:  # pragma: no cover - 正则保证了一定能转
            continue
    return values


def find_unverified_numbers(prose: str, material: str) -> list[str]:
    """返回正文里出现的、但材料里找不到出处的数字（**保持出现顺序、去重**）。

    Args:
        prose: 模型写的那段正文。
        material: 写这段正文时给它的全部材料（`SectionPlan.brief`）。

    Returns:
        原文里的数字**写法**（不是解析后的值），所以界面能照原样显示给用户看。
        空列表表示没发现问题 —— 注意这**不等于**「这段文字可信」，
        它只说明「没有明显像数据的数字对不上」。
    """
    known = _values(material)
    seen: set[str] = set()
    unverified: list[str] = []

    for token in _NUMBER.findall(prose):
        if not _looks_like_data(token) or token in seen:
            continue
        seen.add(token)
        if float(token) not in known:
            unverified.append(token)
    return unverified

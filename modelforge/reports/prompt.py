"""报告写作的提示词 —— **和对话的人设刻意分开**。

════════════════════════════════════════════════════════════════════════
为什么不能复用 `SYSTEM_PROMPT`（ADR-017）
════════════════════════════════════════════════════════════════════════

`agents/prompts.py` 里的那段提示词把 Agent 定成「蒟蒻」——一个自称「蒟蒻」、
说话谦逊、每个决策点都停下来问用户的助手。那是**对话**要的性格，
而报告是**要交上去的论文**：

    对话里对：  「这个蒟蒻拿不准，要不咱们先试试熵权法？」
    报告里错：  「本蒟蒻采用熵权法确定指标权重。」

一份数模论文里出现网络自称，是直接扣分的事。所以报告的语体是分开的一段。

**但有一件事必须原样继承**：那条「绝不编造数据」的规矩。而且它在报告里
比在对话里更重要 —— 对话里编一个数会被用户当场看见，报告里编一个数会
印在纸上交上去。所以下面把这条写得更死，并且给了它一个可执行的形状。

════════════════════════════════════════════════════════════════════════
为什么是「一节一次调用」，而不是「整篇一次」
════════════════════════════════════════════════════════════════════════

  · **材料刚好够** —— 每一节只看见自己那部分事件，不用把几十轮对话
    塞进一个请求里
  · **失败局部化** —— 某一节生成失败，其余三节照旧成稿
  · **进度看得见** —— 用户看到报告一节一节长出来，而不是转圈等半分钟
  · **别节的东西写不进来** —— 结论那一节的上下文里没有第二章的候选列表，
    想跑题都难
"""

from __future__ import annotations

__all__ = ["REPORT_SYSTEM_PROMPT", "section_message"]


REPORT_SYSTEM_PROMPT = """你在为一篇数学建模竞赛论文撰写草稿的某个章节。

【语体】
- 用**学术论文的中文**：第三人称、陈述句、不用口语和网络用语。
  不要自称「我」、「我们」或任何拟人化的助手名号。
- 不要写标题（章节名由程序加）、不要写「以下是本章内容」这类引导语。
  直接进入正文。
- 篇幅克制：一段到三段，200～500 字。论文的正文要让位给图表和公式，
  不是把材料复述一遍。

【最重要的一条规矩：绝不编造数据】
你拿到的材料是**唯一可信的信息来源**。除此之外你不掌握任何事实。

- **不要写材料里没有的数字。** 一个都不行。
  需要某个数支撑论点但材料里没有 → 就把这个论点写成定性的，
  或者直接说「这一点还需要补充计算」。
- **不要把材料里的数字抄进正文。** 它们会由程序原样附在正文后面
  （代码、输出、图都是），你抄一遍只会让同一个数字在一份报告里出现两次，
  而且给了自己抄错的机会。你要做的是**说明它们意味着什么**。
- **不确定就写不确定。** 材料不足以支撑结论时，写「目前的结果还不足以
  给出确定结论」。一篇诚实的论文，比一篇言之凿凿但站不住的论文分数高。

【不要做的事】
- 不要编造参考文献、方法名、或你不确定名字的模型。
- 不要评价自己的工作（「本文的方法非常有效」）。把结果摆出来，让读者判断。
- 不要提及「材料」「输入」「上面给的」这类工程词汇 ——
  读者看到的是一篇论文，不知道有中间材料这回事。"""


def section_message(brief: str, *, title: str) -> str:
    """拼出「请写这一节」的那条请求。

    `title` 会出现在提示里，是为了让模型知道**这一节在整篇里的位置** ——
    同样是材料，「一、问题重述」和「四、结论」的写法完全不同。
    """
    return f"""请撰写这一节：**{title}**

以下是这一节的全部材料。材料之外你不掌握任何事实。

────── 材料开始 ──────
{brief}
────── 材料结束 ──────

直接输出这一节的正文。不要写标题，不要复述材料里的数字，不要编造
材料以外的任何数字或事实。"""

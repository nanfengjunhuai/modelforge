"""Agent 层：**驱动一轮对话**。

════════════════════════════════════════════════════════════════════════
这里原来规划着五个模块，最后一个没落地在这里
════════════════════════════════════════════════════════════════════════

    decompose.py  —— 拆题：读懂赛题，抽出已知/未知/目标/约束
    select.py     —— 选模：从候选模型中给方案 + 理由
    solve.py      —— 求解：写代码交给沙箱跑
    verify.py     —— 验证：结果合理吗？灵敏度如何？
    write.py      —— 成文：生成论文级报告

前四个**从来没有作为独立模块存在过**，而且这不是欠账 —— 它们后来变成了
`loop.py` 里的一轮对话。理由和 M4 没做那个五节点状态机是同一条
（见 `modelforge/core/__init__.py`）：与其把流程写死成五个节点，
不如给模型一个 `ask_user` 工具，**由它自己决定在哪一步停下来问**
（ADR-010）。实测下来它问的问题比预想的有信息量。

所以现在这个包里只有两个模块：

    prompts.py   蒟蒻的人设（对话用；报告是另一段，见 ADR-017）
    loop.py      一轮 Agent 循环：模型 → 工具 → 回填 → 再问

════════════════════════════════════════════════════════════════════════
那「成文」去哪了
════════════════════════════════════════════════════════════════════════

**它落在了 `modelforge/reports/`，不是这里。** M6a 做的。

它不是 Agent 在对话中做的某一步，而是**从已落盘的事件里投影出来的**：

  · 它不需要工具（不跑代码、不问用户），所以不需要 Agent 循环
  · 它不在对话里发生 —— 用户点「生成报告」时，那一轮对话早就结束了
  · 它读的是**整个会话的日志**，而 `loop.py` 读的是投影出来的消息历史

把它放这里的话，`agents/` 就有了两个不相干的职责；放出去之后，
这个包保持「驱动一轮对话」这一件事不变。

注意：Agent 不直接调用模型，而是通过 ``modelforge.providers`` 拿到统一的流式接口。
"""
